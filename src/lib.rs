    /// Accept the latest committed snapshot from every repository in a session
    /// into the explicitly selected host branch. Unlike `stop`, this keeps a
    /// running guest and its isolated Git metadata intact for further work.
    pub fn accept(&self, id: &str, target: &str, options: AcceptOptions) -> Result<()> {
        let mut session = self.load_session(id)?;
        let targets = vec![target.to_owned(); session.repos.len()];
        let repos = session.repos.clone();
        self.accept_snapshots(&mut session, &repos, &targets, options)
    }

    /// Interactively select a session from the current repository, then
    /// accept every repository in that development machine. With no explicit
    /// branch each host repository uses its own checked-out branch, which
    /// supports sessions spanning repositories with different default names.
    pub fn accept_all_from_repository(
        &self,
        input: &Path,
        target: Option<&str>,
        options: AcceptOptions,
    ) -> Result<()> {
        let Some((mut session, _)) =
            self.select_repository_worktree(input, "accept all worktrees from", None)?
        else {
            return Ok(());
        };
        let targets = session
            .repos
            .iter()
            .map(|repo| match target {
                Some(target) => Ok(target.to_owned()),
                None => {
                    let branch = self.git.current_branch(&repo.source)?;
                    if branch.is_empty() {
                        bail!(
                            "cannot accept all: host repository {} is detached; check out a branch or pass --into <branch>",
                            repo.source.display()
                        );
                    }
                    Ok(branch)
                }
            })
            .collect::<Result<Vec<_>>>()?;

        println!(
            "Accept every repository from session {} into these host branches:",
            session.id
        );
        for (repo, target) in session.repos.iter().zip(&targets) {
            println!("  {}: {} -> {target}", repo.name, repo.branch);
        }
        let action = if options.merge {
            "Merge"
        } else {
            "Fast-forward"
        };
        print!(
            "{action} all {} worktrees from session {}? [y/N]: ",
            session.repos.len(),
            session.id
        );
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            println!("accept all cancelled.");
            return Ok(());
        }
        let repos = session.repos.clone();
        self.accept_snapshots(&mut session, &repos, &targets, options)
    }

    /// Interactively accept exactly the repository selected by the current
    /// directory. This avoids surprising cross-repository acceptance when a
    /// multi-repository session is selected from one checkout.
    pub fn accept_from_repository(
        &self,
        input: &Path,
        target: Option<&str>,
        options: AcceptOptions,
    ) -> Result<()> {
        let repository = Config::repository_root(input)?;
        let target = match target {
            Some(target) => target.to_owned(),
            None => self.git.current_branch(&repository)?,
        };
        if target.is_empty() {
            bail!(
                "{} is detached; check out the branch to accept into or pass --into <branch>",
                repository.display()
            );
        }
        let action = if options.merge {
            "merge"
        } else {
            "fast-forward"
        };
        let selection_action = format!("{action} `{target}` from");
        let Some((mut session, repo)) =
            self.select_repository_worktree(input, &selection_action, None)?
        else {
            return Ok(());
        };
        let Some(options) = self.prompt_merge_if_diverged(&session, &repo, &target, options)?
        else {
            return Ok(());
        };
        let action = if options.merge {
            "Merge"
        } else {
            "Fast-forward"
        };
        print!(
            "{action} `{target}` to {} from session {}? [y/N]: ",
            repo.branch, session.id
        );
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            println!("accept cancelled.");
            return Ok(());
        }
        self.accept_snapshots(
            &mut session,
            std::slice::from_ref(&repo),
            &[target],
            options,
        )
    }

    /// Repository-scoped acceptance is interactive already. If its clean host
    /// branch cannot fast-forward, offer the explicit merge right there rather
    /// than making the user repeat the selection with `--merge`.
    fn prompt_merge_if_diverged(
        &self,
        session: &Session,
        repo: &RepoState,
        target: &str,
        mut options: AcceptOptions,
    ) -> Result<Option<AcceptOptions>> {
        if options.merge {
            return Ok(Some(options));
        }
        // Import first so the ancestry question covers every guest commit
        // created since the prior accept, while leaving the host branch alone.
        self.git.import_guest_commits(repo)?;
        self.git.preflight_accept_target(repo, target)?;
        if (!options.stash_host && !self.git.host_is_clean(repo)?)
            || self.git.snapshot_can_fast_forward(repo, target)?
        {
            return Ok(Some(options));
        }
        println!(
            "Fast-forward cannot accept `{target}` because it has diverged from session branch `{}`.",
            repo.branch
        );
        println!(
            "A merge creates a host merge commit. If Git reports conflicts, the jbox session remains available and `jbox accept --continue` or `jbox accept --abort` completes recovery."
        );
        print!(
            "Create a merge from {} for session {} now? [y/N]: ",
            repo.branch, session.id
        );
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            println!("accept cancelled. No host branch was changed.");
            return Ok(None);
        }
        options.merge = true;
        Ok(Some(options))
    }

    /// Complete a host merge created by an earlier `jbox accept --merge`.
    /// The selected jbox session is retained throughout. Git itself remains
    /// responsible for the user's conflict resolution content.
    pub fn continue_accept_from_repository(&self, input: &Path) -> Result<()> {
        let Some((mut session, repo)) =
            self.select_paused_acceptance_worktree(input, "continue")?
        else {
            return Ok(());
        };
        let Some(conflicts) = self.git.host_merge_conflicts(&repo)? else {
            bail!(
                "no acceptance merge is paused in {}; choose the worktree whose host checkout is merging",
                repo.source.display()
            );
        };
        if !conflicts.is_empty() {
            println!(
                "Acceptance is paused for session {}. Host merge conflicts in {}:\n{}",
                session.id,
                repo.source.display(),
                conflicts
            );
            bail!(
                "resolve and stage those files, then rerun `jbox accept --continue`; use `jbox accept --abort` to abandon the host merge"
            );
        }
        print!(
            "Commit the staged host merge for session {} and keep its jbox worktree? [y/N]: ",
            session.id
        );
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            println!("continue acceptance cancelled. The host merge remains paused.");
            return Ok(());
        }
        self.git.continue_host_merge(&repo)?;
        println!(
            "completed acceptance merge for {}. Jbox session {} remains retained.",
            repo.name, session.id
        );
        self.touch(&mut session)
    }

    /// Abort only the pending host-side merge created by `accept --merge`.
    /// The generated worktree and its session branch remain available for a
    /// later rebase, merge, or inspection.
    pub fn abort_accept_from_repository(&self, input: &Path) -> Result<()> {
        let Some((mut session, repo)) = self.select_paused_acceptance_worktree(input, "abort")?
        else {
            return Ok(());
        };
        let Some(conflicts) = self.git.host_merge_conflicts(&repo)? else {
            bail!(
                "no acceptance merge is paused in {}; choose the worktree whose host checkout is merging",
                repo.source.display()
            );
        };
        println!(
            "Abort the host merge for session {} in {}. The jbox session branch {} stays retained.{}",
            session.id,
            repo.source.display(),
            repo.branch,
            if conflicts.is_empty() {
                ""
            } else {
                " Unresolved files are present."
            }
        );
        print!("Abort this host merge? [y/N]: ");
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            println!("abort acceptance cancelled. The host merge remains paused.");
            return Ok(());
        }
        self.git.abort_host_merge(&repo)?;
        println!(
            "aborted host merge for {}. Jbox session {} and branch {} remain retained.",
            repo.name, session.id, repo.branch
        );
        self.touch(&mut session)
    }

    fn accept_snapshots(
        &self,
        session: &mut Session,
        repos: &[RepoState],
        targets: &[String],
        options: AcceptOptions,
    ) -> Result<()> {
        if repos.len() != targets.len() {
            bail!("internal error: every accepted repository needs an acceptance target");
        }

        // Detect every unresolved conflict before making a checkpoint commit in
        // any sibling worktree. This prevents a multi-repository command from
        // producing a partial set of surprise commits.
        if options.checkpoint {
            for repo in repos {
                self.git.validate_session_checkpoint(repo)?;
            }
            for repo in repos {
                if self.git.checkpoint_session_changes(repo, &session.id)? {
                    println!("checkpointed generated worktree changes for {}", repo.name);
                }
            }
        }
        // Import every guest branch, and preflight every host checkout, before
        // moving any host ref. A divergent sibling therefore leaves every host
        // repository untouched.
        for repo in repos {
            self.git.import_guest_commits(repo)?;
        }

        // Validate checked-out target branches before temporarily moving host
        // files into a stash. The actual clean-check runs after the stash.
        if options.stash_host {
            for (repo, target) in repos.iter().zip(targets) {
                self.git.preflight_accept_target(repo, target)?;
            }
        }

        let mut stashes = Vec::new();
        if options.stash_host {
            for repo in repos {
                if let Some(stash) = self.git.stash_host_changes(repo, &session.id)? {
                    println!(
                        "preserved uncommitted host changes for {} in a temporary stash",
                        repo.name
                    );
                    stashes.push((repo, stash));
                }
            }
        }

        let accept_result = (|| -> Result<()> {
            for (repo, target) in repos.iter().zip(targets) {
                if options.merge {
                    self.git.preflight_merge_snapshot(repo, target)?;
                } else {
                    self.git.preflight_accept_snapshot(repo, target)?;
                }
            }
            for (repo, target) in repos.iter().zip(targets) {
                if options.merge {
                    self.git.merge_snapshot(repo, target)?;
                } else {
                    self.git.fast_forward_snapshot(repo, target)?;
                }
                let verb = if options.merge { "merged" } else { "accepted" };
                println!(
                    "{verb} {} snapshot from {} into {}",
                    repo.name, repo.branch, target
                );
            }
            Ok(())
        })();

        if let Err(error) = accept_result {
            if !stashes.is_empty() {
                eprintln!(
                    "host changes remain safely stashed because acceptance did not finish; inspect `git stash list` in each affected host repository before retrying"
                );
            }
            return Err(error);
        }

        for (repo, stash) in stashes {
            self.git.restore_host_stash(repo, &stash)?;
            println!("restored preserved host changes for {}", repo.name);
        }

        self.touch(session)?;
        if session.state == SessionState::Running {
            println!(
                "jbox session {} remains running for further work.",
                session.id
            );
        }
        Ok(())
    }

    /// Rebase a single selected session worktree from its host repository. A
    /// live guest is explicitly stopped first so its isolated Git metadata is
    /// imported and restored before the host-side rebase changes the branch.
    pub fn rebase_from_repository(&self, input: &Path, onto: Option<&str>) -> Result<()> {
        let repository = Config::repository_root(input)?;
        let onto = match onto {
            Some(branch) => branch.to_owned(),
            None => self.git.current_branch(&repository)?,
        };
        if onto.is_empty() {
            bail!("{} is detached; pass --onto <branch>", repository.display());
        }
        let selection_action = format!("rebase onto `{onto}`");
        let Some((session, repo)) =
            self.select_repository_worktree(input, &selection_action, None)?
        else {
            return Ok(());
        };
        print!(
            "Rebase {} from session {} onto `{onto}`? [y/N]: ",
            repo.branch, session.id
        );
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            println!("rebase cancelled.");
            return Ok(());
        }
        if session.state == SessionState::Running {
            println!(
                "stopping {} to safely synchronize its Git metadata...",
                session.id
            );
            self.stop(&session.id)?;
        }
        self.git.rebase_worktree(&repo, &onto)?;
        println!(
            "rebased {} onto `{onto}`. Run `jbox accept` to fast-forward it.",
            repo.branch
        );
        Ok(())
    }

    /// Open a host-local shell in the matching retained worktree. This is an
    /// intentional escape hatch for resolving a paused rebase or merge before
    /// a guest can safely be resumed. It never starts a container or changes
    /// the worktree itself.
    pub fn resolve(&self, id: &str, input: &Path) -> Result<()> {
        let session = self.load_session(id)?;
        let repository = Config::repository_root(input)?;
        let repo = session
            .repos
            .iter()
            .find(|repo| repo.source == repository)
            .ok_or_else(|| {
                anyhow::anyhow!(
                    "session {id} has no worktree for {}; run `jbox resolve` from a participating repository",
                    repository.display()
                )
            })?;
        self.resolve_worktree(&session, repo)
    }

    pub fn resolve_from_repository(&self, input: &Path) -> Result<()> {
        let Some((session, repo)) = self.select_repository_worktree(input, "resolve", None)? else {
            return Ok(());
        };
        self.resolve_worktree(&session, &repo)
    }

    fn resolve_worktree(&self, session: &Session, repo: &RepoState) -> Result<()> {
        if !io::stdin().is_terminal() || !io::stdout().is_terminal() {
            bail!("`jbox resolve` needs an interactive terminal");
        }
        println!(
            "Opening a local host shell in retained worktree {} for session {}.",
            repo.worktree.display(),
            session.id
        );
        println!(
            "No guest is started and jbox changes no files. Resolve the Git operation, run `git rebase --continue` or `git merge --continue`, then exit and run `jbox resume`."
        );
        let status = Command::new("bash")
            .args(["--noprofile", "--norc"])
            .current_dir(&repo.worktree)
            .env("JBOX_RETAINED_SESSION", &session.id)
            .env("JBOX_RETAINED_WORKTREE", &repo.worktree)
            .status()
            .context("could not open a local shell in the retained worktree")?;
        if !status.success() {
            bail!("retained worktree shell exited with {status}");
        }
        Ok(())
    }

