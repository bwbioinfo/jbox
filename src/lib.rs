    #[test]
    fn jbox_terminal_identity_is_distinct_and_control_safe() {
        let session = terminal_label("calm-fox\u{1b}]2;not-a-title\u{7}");
        let mount = terminal_label("/workspace/project\nnext");

        assert_eq!(session, "calm-fox]2;not-a-title");
        assert_eq!(mount, "/workspace/projectnext");
        assert_eq!(
            jbox_terminal_title(&session, &mount),
            "[📦 JBOX] calm-fox]2;not-a-title · /workspace/projectnext"
        );
    }

