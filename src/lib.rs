    fn sessions_for_repository(&self, repository: &Path) -> Result<Vec<(Session, RepoState)>> {
        Ok(self
            .list_sessions()?
            .into_iter()
            .flat_map(|session| {
                let repositories = session
                    .repos
                    .iter()
                    .filter(|repo| repo.source == repository)
                    .cloned()
                    .collect::<Vec<_>>();
                repositories
                    .into_iter()
                    .map(move |repo| (session.clone(), repo))
            })
            .collect())
    }

