/// Make an isolated guest unmistakable before its Jcode TUI takes over the
/// terminal. Jcode's supported SSH CLI deliberately has no TUI-theme or
/// header-decoration flag, so jbox owns only terminal chrome outside the TUI.
/// The OSC title remains visible in terminal tabs, multiplexers, and desktop
/// window lists for the duration of the attached client.
fn render_jbox_session_chrome(session_id: &str, mount: &str) -> Result<()> {
    if !io::stdout().is_terminal() {
        return Ok(());
    }
    let session_id = terminal_label(session_id);
    let mount = terminal_label(mount);
    let title = jbox_terminal_title(&session_id, &mount);
    let width = 68;
    let line = "─".repeat(width - 2);
    let mut stdout = io::stdout().lock();
    writeln!(stdout, "\n┌{line}┐")?;
    writeln!(stdout, "│  📦 JBOX GUEST  {session_id}")?;
    writeln!(stdout, "│  Kata-isolated workspace: {mount}")?;
    writeln!(stdout, "└{line}┘")?;
    // BEL terminates OSC 2 across common terminals and tmux/screen pass it
    // through. Labels are strictly sanitized before interpolation.
    write!(stdout, "\x1b]2;{title}\x07")?;
    stdout.flush()?;
    Ok(())
}

/// Session IDs are generated by jbox and guest paths are configuration-
/// validated, but sanitize defensively because OSC payloads must never accept
/// terminal-control characters from persisted state.
fn terminal_label(value: &str) -> String {
    let label = value
        .chars()
        .filter(|character| !character.is_control())
        .take(80)
        .collect::<String>();
    if label.is_empty() {
        "jbox-session".into()
    } else {
        label
    }
}

fn jbox_terminal_title(session_id: &str, mount: &str) -> String {
    format!("[📦 JBOX] {session_id} · {mount}")
}

fn guest_jcode_config(jcode: &config::Jcode) -> String {
    let mut lines =
        vec!["# Generated for this jbox session. Do not store credentials here.".into()];
    lines.push("[provider]".into());
    for (key, value) in [
        ("default_provider", jcode.default_provider.as_deref()),
        ("default_model", jcode.default_model.as_deref()),
        (
            "openai_reasoning_effort",
            jcode.openai_reasoning_effort.as_deref(),
        ),
        ("openai_service_tier", jcode.openai_service_tier.as_deref()),
    ] {
        if let Some(value) = value {
            lines.push(format!("{key} = {}", toml::Value::String(value.into())));
        }
    }
    format!("{}\n", lines.join("\n"))
}

fn init_dockerfile(tools: &[String]) -> String {
    let mut dockerfile = String::from(
        "ARG JBOX_BASE_IMAGE\nFROM ${JBOX_BASE_IMAGE}\n\n# This image extends jbox's Debian-based jcode runtime.\n",
    );
    if tools.is_empty() {
        dockerfile.push_str(
            "# Add tools with a command such as:\n# RUN apt-get update && apt-get install -y --no-install-recommends ripgrep jq && rm -rf /var/lib/apt/lists/*\n",
        );
    } else {
        dockerfile.push_str(
            "RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\\n",
        );
        for tool in tools {
            dockerfile.push_str(&format!("    {tool} \\\n"));
        }
        dockerfile.push_str("    && rm -rf /var/lib/apt/lists/*\n");
    }
    dockerfile
}

