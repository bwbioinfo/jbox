    /// Resume a stopped session from its retained worktrees. The worktree
    /// branch and image are reused. A fresh session SSH key and runtime state
    /// are created. A visible dirty worktree gets an explicit checkpoint offer
    /// before recreating its isolated guest Git metadata.
    pub fn resume(&self, id: &str) -> Result<()> {
        let mut session = self.load_session(id)?;
        if session.state == SessionState::Running {
            bail!("session {id} is already running; use `jbox attach {id}`");
        }
        if self.engine.is_running(&session.container_name)? {
            bail!(
                "runtime container for {id} is unexpectedly still running; use `jbox attach {id}` or `jbox stop {id}` first"
            );
        }
        let (config, primary) = Config::load(&session.config_path)?;
        self.validate_resume_config(&session, &config, &primary)?;
        self.engine.check()?;
        if config.git.network && config.git.credentials == "jbox" {
            self.paths.ensure_credentials()?;
        }
        let author = config.git.author.resolve()?;
        self.checkpoint_dirty_worktrees_before_resume(&session)?;
        for repo in &session.repos {
            if let Err(error) = self
                .git
                .prepare_retained_worktree_for_guest(repo, &author)
                .with_context(|| format!("could not prepare retained worktree {}", repo.name))
            {
                self.restore_retained_metadata(&session.repos);
                return Err(error);
            }
        }

        let ssh = self.paths.session_ssh_dir(&session.id);
        self.clear_stale_runtime_sockets(&ssh)?;
        let _ = std::fs::remove_dir_all(&ssh);
        if let Err(error) = self.paths.create_session_ssh(&ssh) {
            self.restore_retained_metadata(&session.repos);
            return Err(error).context("could not create resumed session SSH credentials");
        }
        let ssh_agent_pid = match self.paths.start_session_ssh_agent(&ssh) {
            Ok(pid) => pid,
            Err(error) => {
                self.restore_retained_metadata(&session.repos);
                return Err(error);
            }
        };
        let spec = match self.container_spec(
            &config,
            &session.repos,
            &session.container_name,
            &ssh,
            SessionLaunch {
                image: session.image.clone(),
                ssh_host: session.ssh_host.clone(),
                reuse_runtime_state: true,
            },
        ) {
            Ok(spec) => spec,
            Err(error) => {
                self.paths.stop_session_ssh_agent(ssh_agent_pid);
                self.restore_retained_metadata(&session.repos);
                return Err(error);
            }
        };
        let port = match self.engine.start(&spec) {
            Ok(port) => port,
            Err(error) => {
                self.paths.stop_session_ssh_agent(ssh_agent_pid);
                self.restore_retained_metadata(&session.repos);
                return Err(error);
            }
        };
        let known_hosts_tag = match self
            .paths
            .trust_session_host(&session.ssh_host, &session.id)
        {
            Ok(tag) => tag,
            Err(error) => {
                let _ = self.engine.stop(&session.container_name);
                self.paths.stop_session_ssh_agent(ssh_agent_pid);
                self.restore_retained_metadata(&session.repos);
                return Err(error);
            }
        };
        session.state = SessionState::Running;
        session.ssh_port = port;
        session.ssh_agent_pid = ssh_agent_pid;
        session.known_hosts_tag = known_hosts_tag;
        self.touch(&mut session)?;
        println!(
            "jbox session {} resumed on {}:{}",
            session.id, session.ssh_host, session.ssh_port
        );
        println!("Use `jbox attach {}` to reconnect.", session.id);
        Ok(())
    }

    /// Recreating isolated guest Git metadata includes a hard reset. Never do
    /// that over agent files. Ordinary changes can instead be checkpointed on
    /// the retained session branches with an explicit confirmation. Validate
    /// every candidate first, so an unresolved sibling operation cannot leave
    /// a partial set of new commits.
    fn checkpoint_dirty_worktrees_before_resume(&self, session: &Session) -> Result<()> {
        let mut changed = Vec::new();
        for repo in &session.repos {
            if self.git.validate_session_checkpoint(repo)? {
                changed.push(repo);
            }
        }
        if changed.is_empty() {
            return Ok(());
        }
        if !io::stdin().is_terminal() || !io::stdout().is_terminal() {
            bail!(
                "cannot resume {}: {} retained worktree(s) have uncommitted changes; run `jbox resume {}` in an interactive terminal to checkpoint them, or commit/stash them manually",
                session.id,
                changed.len(),
                session.id
            );
        }
        println!(
            "Session {} has uncommitted changes in retained worktrees:",
            session.id
        );
        for repo in &changed {
            println!("  - {} ({})", repo.name, repo.worktree.display());
        }
        println!(
            "Resuming recreates guest Git metadata. Jbox can preserve these files by committing them only to their session branch."
        );
        print!(
            "Checkpoint these changes, then resume session {}? [y/N]: ",
            session.id
        );
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !matches!(confirmed.trim(), "y" | "Y" | "yes" | "YES") {
            bail!(
                "resume cancelled. No worktree files or branches were changed; commit or stash the retained changes before retrying"
            );
        }
        for repo in changed {
            if self
                .git
                .checkpoint_session_changes_for_resume(repo, &session.id)?
            {
                println!("checkpointed retained changes for {}", repo.name);
            }
        }
        Ok(())
    }

