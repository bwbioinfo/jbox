    fn test_app(root: &Path) -> App {
        let data = root.join("jbox-data");
        let paths = JboxPaths {
            cache: root.join("jbox-cache"),
            sessions: data.join("sessions"),
            credentials: data.join("credentials"),
            data,
        };
        App {
            state: StateStore::new(paths.clone()),
            paths,
            git: Git,
            engine: DockerEngine,
        }
    }

    #[test]
    fn prime_uses_fixed_module_arguments_with_or_without_sudo() {
        let root = prime_module_command(true);
        assert_eq!(root.get_program(), "modprobe");
        assert_eq!(
            root.get_args()
                .map(|arg| arg.to_string_lossy())
                .collect::<Vec<_>>(),
            ["vhost_vsock", "vhost_net"]
        );

        let user = prime_module_command(false);
        assert_eq!(user.get_program(), "sudo");
        assert_eq!(
            user.get_args()
                .map(|arg| arg.to_string_lossy())
                .collect::<Vec<_>>(),
            ["modprobe", "vhost_vsock", "vhost_net"]
        );
    }

    #[test]
    fn prime_prompt_requires_only_the_modules_needed_by_the_session() {
        assert!(missing_prime_requirements(true, true, true).is_empty());
        assert_eq!(
            missing_prime_requirements(true, false, false),
            ["the VSOCK device", "the vhost_net kernel module"]
        );
        assert_eq!(
            missing_prime_requirements(false, true, false),
            Vec::<&str>::new()
        );
        assert!(prime_confirmation("yes\n"));
        assert!(prime_confirmation("Y"));
        assert!(!prime_confirmation("yesterday"));
        assert!(!prime_confirmation(""));
    }

    fn test_session(id: &str, source: PathBuf) -> Session {
        let now = Utc::now();
        Session {
            version: 1,
            id: id.into(),
            state: SessionState::Stopped,
            container_name: format!("jbox-{id}"),
            ssh_host: "127.0.0.2".into(),
            ssh_port: 22,
            ssh_agent_pid: 0,
            known_hosts_tag: format!("# jbox:{id}"),
            created_at: now,
            last_activity_at: now,
            ttl_seconds: 86_400,
            config_path: source.join(".jbox.toml"),
            launch_directory: Some(source.clone()),
            image: "test".into(),
            repos: vec![RepoState {
                name: "repo".into(),
                worktree: source.join("worktree"),
                mount: "/workspace/repo".into(),
                branch: format!("jbox/{id}/repo"),
                base_commit: "deadbeef".into(),
                host_gitfile: source.join("host-gitfile"),
                beads_snapshot: None,
                beads_bootstrap: Vec::new(),
                source,
            }],
            jcode_default_provider: None,
            jcode_default_model: None,
        }
    }

    #[test]
    fn repository_accept_lists_only_sessions_for_the_current_repository() {
        let temp = tempdir().unwrap();
        let app = test_app(temp.path());
        let current = temp.path().join("current");
        let other = temp.path().join("other");
        app.state
            .save(&test_session("current-session", current.clone()))
            .unwrap();
        app.state
            .save(&test_session("other-session", other))
            .unwrap();

        let candidates = app.sessions_for_repository(&current).unwrap();
        assert_eq!(candidates.len(), 1);
        assert_eq!(candidates[0].0.id, "current-session");
    }

    #[test]
    fn repository_list_shows_complete_matching_sessions_only() {
        let temp = tempdir().unwrap();
        let app = test_app(temp.path());
        let current = temp.path().join("current");
        let other = temp.path().join("other");
        let mut project = test_session("project-session", current.clone());
        project.repos.push(RepoState {
            name: "sibling".into(),
            source: other.clone(),
            worktree: temp.path().join("sibling-worktree"),
            mount: "/workspace/sibling".into(),
            branch: "jbox/project-session/sibling".into(),
            base_commit: "deadbeef".into(),
            host_gitfile: temp.path().join("sibling-gitfile"),
            beads_snapshot: None,
            beads_bootstrap: Vec::new(),
        });
        app.state.save(&project).unwrap();
        app.state
            .save(&test_session(
                "unrelated-session",
                temp.path().join("unrelated"),
            ))
            .unwrap();

        let listed = app.list_sessions_for_repository(&current).unwrap();
        assert_eq!(listed.len(), 1);
        assert_eq!(listed[0].id, "project-session");
        assert_eq!(listed[0].repos.len(), 2);
        assert_eq!(app.list_sessions().unwrap().len(), 2);
    }

    #[test]
    fn session_list_shows_launch_directory_and_handles_legacy_sessions() {
        let temp = tempdir().unwrap();
        let launch_directory = temp.path().join("launched-here");
        let current = temp.path().join("current");
        let mut current_session = test_session("current-session", current);
        current_session.launch_directory = Some(launch_directory.clone());

        let legacy_json = serde_json::to_value(test_session("legacy-session", temp.path().join("legacy"))).unwrap();
        let mut legacy_json = legacy_json;
        legacy_json
            .as_object_mut()
            .unwrap()
            .remove("launch_directory");
        let legacy_session = serde_json::from_value::<Session>(legacy_json).unwrap();
        assert!(legacy_session.launch_directory.is_none());

        let output = format_session_list("No jbox sessions.", &[current_session, legacy_session]);
        assert!(output.starts_with("ID\tSTATE\tLAST ACTIVITY\tREPOSITORIES\tHOST DIRECTORY\n"));
        assert!(output.contains(&format!("\t{}\n", launch_directory.display())));
        assert!(output.contains("legacy-session\tStopped"));
        assert!(output.contains("\t-\n"));
    }

    #[test]
    fn init_creates_a_config_and_tooling_image_without_overwriting() {
        let temp = tempdir().unwrap();
        assert!(
            Command::new("git")
                .args(["init", temp.path().to_str().unwrap()])
                .status()
                .unwrap()
                .success()
        );
        let app = test_app(temp.path());
        app.init(temp.path(), &["ripgrep".into(), "jq".into()])
            .unwrap();

        assert!(temp.path().join(".jbox.toml").is_file());
        let (config, _) = Config::load(temp.path()).unwrap();
        assert_eq!(config.jcode.skills.len(), 1);
        assert_eq!(config.jcode.skills[0].repository, "bwbioinfo/skills");
        assert_eq!(config.jcode.skills[0].skill, None);
        let dockerfile = std::fs::read_to_string(temp.path().join(".jbox/Dockerfile")).unwrap();
        assert!(dockerfile.contains("FROM ${JBOX_BASE_IMAGE}"));
        assert!(dockerfile.contains("    ripgrep \\"));
        assert!(dockerfile.contains("    jq \\"));
        app.init(temp.path(), &[]).unwrap();
    }

