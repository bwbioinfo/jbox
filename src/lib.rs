    pub fn doctor(&self) -> Result<()> {
        println!("jbox state: {}", self.paths.data.display());
        println!(
            "KVM: {}",
            if Path::new("/dev/kvm").exists() {
                "available"
            } else {
                "missing"
            }
        );
        println!(
            "VSOCK: {}",
            if Path::new("/dev/vhost-vsock").exists() {
                "available"
            } else {
                "missing: run `jbox prime`"
            }
        );
        let vhost_net = module_loaded("vhost_net");
        println!(
            "Kata guest networking: {}",
            if vhost_net {
                "vhost_net loaded"
            } else {
                "vhost_net missing: run `jbox prime`"
            }
        );
        match self.engine.check() {
            Ok(()) => println!("Docker + Kata runtime: ready"),
            Err(error) => {
                println!("Docker + Kata runtime: unavailable");
                println!("  {error:#}");
                println!(
                    "  Install Kata, register it as Docker's `kata` OCI runtime, then run `docker info`."
                );
            }
        }
        println!(
            "Network: Docker bridge grants Internet access but cannot enforce host/LAN denial by itself. Apply host firewall policy before treating this boundary as strict."
        );
        Ok(())
    }

    /// Load the Kata VSOCK and guest-networking modules for the current boot.
    /// This deliberately has no persistence side effects under `/etc`.
    pub fn prime(&self) -> Result<()> {
        println!("Loading Kata VSOCK and guest-networking modules for this boot...");
        let status = prime_module_command(current_euid_is_root()?)
            .status()
            .context("could not invoke modprobe; install sudo or run this command as root")?;
        if !status.success() {
            bail!(
                "could not load Kata networking modules; run `sudo modprobe vhost_vsock vhost_net` and inspect the error above"
            );
        }
        if !Path::new("/dev/vhost-vsock").exists() || !module_loaded("vhost_net") {
            bail!(
                "Kata networking modules did not become available after modprobe; inspect `dmesg` and run `jbox doctor`"
            );
        }
        println!(
            "Kata networking modules are ready for this boot. To load them after every reboot, add `vhost_vsock` and `vhost_net` to a root-owned /etc/modules-load.d configuration."
        );
        self.doctor()
    }

    /// Prompt before a session starts when required Kata modules are missing.
    /// Batch invocations never run sudo implicitly.
    fn offer_priming_if_needed(&self, internet: bool) -> Result<()> {
        let missing = missing_prime_requirements(
            internet,
            Path::new("/dev/vhost-vsock").exists(),
            module_loaded("vhost_net"),
        );
        if missing.is_empty() {
            return Ok(());
        }
        let missing = missing.join(" and ");
        if !io::stdin().is_terminal() || !io::stdout().is_terminal() {
            bail!(
                "cannot start a Jbox guest: {missing} is unavailable. Run `jbox prime` in an interactive terminal, then retry"
            );
        }
        println!("Jbox needs {missing} before it can start this guest.");
        print!("Run `jbox prime` now? [y/N]: ");
        io::stdout().flush()?;
        let mut confirmed = String::new();
        io::stdin().read_line(&mut confirmed)?;
        if !prime_confirmation(&confirmed) {
            bail!(
                "Jbox startup cancelled before creating session state. Run `jbox prime` and retry when ready"
            );
        }
        self.prime()
    }

    /// Create missing project-local configuration artifacts. Existing files
    /// are deliberately never replaced.
    pub fn init(&self, input: &Path, tools: &[String]) -> Result<()> {
        let project = Config::repository_root(input)?;
        let config = project.join(".jbox.toml");
        let created_config = !config.exists();
        if config.exists() && !config.is_file() {
            bail!("{} exists but is not a file", config.display());
        }
        for tool in tools {
            if !valid_apt_package(tool) {
                bail!(
                    "invalid --tool `{tool}`: use a simple Debian package name containing only lowercase letters, digits, `+`, `.`, or `-`"
                );
            }
        }

        // A Dockerfile only affects a session when the configuration selects
        // it. Existing configs produced before `jbox init` grew image support
        // often lack an image table, so extend those files without rewriting
        // their comments or unrelated choices. An existing `[image]` table is
        // intentional configuration and must be resolved by its author.
        let add_default_dockerfile_config = if created_config {
            false
        } else {
            match image_dockerfile_setting(&config)? {
                ImageDockerfileSetting::MissingImageTable => true,
                ImageDockerfileSetting::Configured => false,
                ImageDockerfileSetting::MissingDockerfile => bail!(
                    "{} has an [image] table without `dockerfile`; set `dockerfile = \".jbox/Dockerfile\"` before running `jbox init`",
                    config.display()
                ),
            }
        };

        let dockerfile = project.join(".jbox/Dockerfile");
        let created_dockerfile = !dockerfile.exists();
        if dockerfile.exists() && !dockerfile.is_file() {
            bail!("{} exists but is not a file", dockerfile.display());
        }
        if dockerfile.exists() && !tools.is_empty() {
            bail!(
                "{} already exists; add packages there rather than overwriting it",
                dockerfile.display()
            );
        }
        if created_dockerfile {
            std::fs::create_dir_all(
                dockerfile
                    .parent()
                    .context("template Dockerfile has no parent directory")?,
            )?;
            std::fs::write(&dockerfile, init_dockerfile(tools))?;
        }
        if created_config {
            std::fs::write(&config, INIT_CONFIG)?;
            println!("created {}", config.display());
        } else {
            println!("using existing {}", config.display());
            if add_default_dockerfile_config {
                append_default_dockerfile_config(&config)?;
                println!(
                    "added [image].dockerfile = \".jbox/Dockerfile\" to {}",
                    config.display()
                );
            }
        }
        if !created_dockerfile {
            println!("using existing {}", dockerfile.display());
        } else if tools.is_empty() {
            println!(
                "created {}. Add Debian packages with a RUN instruction, then jbox rebuilds the image when it changes.",
                dockerfile.display()
            );
        } else {
            println!(
                "created {} with: {}",
                dockerfile.display(),
                tools.join(", ")
            );
        }
        Ok(())
    }

    /// Create a session from `HEAD`, optionally layering a session-local copy
    /// of the host's visible working tree on top. The source checkout is never
    /// changed by either path.
    pub fn create(
        &self,
        input: &Path,
        include_host_changes: bool,
        launch_directory: &Path,
    ) -> Result<String> {
        let launch_directory = launch_directory.canonicalize().with_context(|| {
            format!(
                "cannot resolve launch directory {}",
                launch_directory.display()
            )
        })?;
        let (config, primary) = Config::load(input)?;
        let git_author = config.git.author.resolve()?;
        if git_author.name.is_none() || git_author.email.is_none() {
            println!(
                "Guest Git author is incomplete. Set host `git config --global user.name` and `user.email`, or override [git.author] in .jbox.toml."
            );
        }
        let session_id = state::new_session_id();

        let mut resolved = vec![ResolvedRepository {
            source: primary.clone(),
            mount: config.workspace.mount.clone(),
            name: config.project_name(&primary),
        }];
        resolved.extend(config.resolve_repositories(&primary)?);
        config.validate_repositories(&resolved)?;
        self.engine.check()?;
        self.offer_priming_if_needed(config.network.internet)?;

        if config.git.network && config.git.credentials == "jbox" {
            self.paths.ensure_credentials()?;
        }
        let image = ImageManager::new(&self.paths).ensure(&config, &primary)?;
        let ssh_host = self.next_ssh_host(&session_id)?;
        let session_dir = self.paths.sessions.join(&session_id);
        let worktrees = session_dir.join("worktrees");
        std::fs::create_dir_all(&worktrees)?;

        // Materialize every source snapshot before constructing guest
        // worktrees. This is deliberately an opt-in operation: normal Jbox
        // sessions retain their reproducible HEAD-only behavior.
        let snapshots = if include_host_changes {
            let snapshot_dir = session_dir.join("runtime/host-change-snapshots");
            let mut snapshots = Vec::with_capacity(resolved.len());
            for repo in &resolved {
                let snapshot = snapshot_dir.join(format!("{}.patch", repo.name));
                match self.git.snapshot_host_changes(&repo.source, &snapshot) {
                    Ok(true) => snapshots.push(Some(snapshot)),
                    Ok(false) => snapshots.push(None),
                    Err(error) => {
                        let _ = std::fs::remove_dir_all(&session_dir);
                        return Err(error).with_context(|| {
                            format!(
                                "could not snapshot uncommitted host changes for {}",
                                repo.source.display()
                            )
                        });
                    }
                }
            }
            snapshots
        } else {
            vec![None; resolved.len()]
        };

        let mut repos: Vec<RepoState> = Vec::with_capacity(resolved.len());
        for (repo, snapshot) in resolved.iter().zip(snapshots.iter()) {
            let worktree = worktrees.join(&repo.name);
            let created = match self
                .git
                .add_worktree(&repo.source, &worktree, &session_id, &repo.name)
                .with_context(|| format!("could not create worktree for {}", repo.source.display()))
            {
                Ok(created) => created,
                Err(error) => {
                    for created_repo in &repos {
                        let _ = self.git.remove_worktree(
                            &created_repo.source,
                            &created_repo.worktree,
                            false,
                        );
                    }
                    return Err(error);
                }
            };
            println!(
                "{}: sandbox branch {} starts at {}",
                repo.name, created.branch, created.commit
            );
            let host_gitfile = session_dir
                .join("host-gitfiles")
                .join(format!("{}.git", repo.name));
            if let Err(error) = self.git.isolate_guest_metadata(
                &repo.source,
                &worktree,
                &created.branch,
                &created.commit,
                &host_gitfile,
                &git_author,
            ) {
                let _ = self.git.remove_worktree(&repo.source, &worktree, false);
                self.cleanup_worktrees(&repos);
                let _ = std::fs::remove_dir_all(&session_dir);
                return Err(error).context("could not prepare isolated guest Git metadata");
            }
            if let Some(snapshot) = snapshot
                && let Err(error) = self.git.apply_host_changes(&worktree, snapshot)
            {
                let provisional = RepoState {
                    name: repo.name.clone(),
                    source: repo.source.clone(),
                    worktree: worktree.clone(),
                    mount: repo.mount.clone(),
                    branch: created.branch.clone(),
                    base_commit: created.commit.clone(),
                    host_gitfile: host_gitfile.clone(),
                    beads_snapshot: None,
                    beads_bootstrap: Vec::new(),
                };
                let _ = self.git.restore_guest_metadata(&provisional);
                let _ = self.git.remove_worktree(&repo.source, &worktree, false);
                self.cleanup_worktrees(&repos);
                let _ = std::fs::remove_dir_all(&session_dir);
                return Err(error).with_context(|| {
                    format!(
                        "could not apply the host-change snapshot to generated worktree {}",
                        worktree.display()
                    )
                });
            }
            if snapshot.is_some() {
                println!(
                    "{}: included uncommitted host changes in sandbox",
                    repo.name
                );
            }
            // `isolate_guest_metadata` hard-resets the generated worktree to
            // its session base. Snapshot Beads *after* that reset so a current
            // host export, including uncommitted task updates, reaches the
            // guest rather than being silently reverted to HEAD.
            let beads_snapshot = match self.git.snapshot_beads_export(&repo.source, &worktree) {
                Ok(snapshot) => snapshot,
                Err(error) => {
                    let provisional = RepoState {
                        name: repo.name.clone(),
                        source: repo.source.clone(),
                        worktree: worktree.clone(),
                        mount: repo.mount.clone(),
                        branch: created.branch.clone(),
                        base_commit: created.commit.clone(),
                        host_gitfile: host_gitfile.clone(),
                        beads_snapshot: None,
                        beads_bootstrap: Vec::new(),
                    };
                    let _ = self.git.restore_guest_metadata(&provisional);
                    let _ = self.git.remove_worktree(&repo.source, &worktree, false);
                    self.cleanup_worktrees(&repos);
                    let _ = std::fs::remove_dir_all(&session_dir);
                    return Err(error).with_context(|| {
                        format!(
                            "could not snapshot Beads task context for {}",
                            repo.source.display()
                        )
                    });
                }
            };
            repos.push(RepoState {
                name: repo.name.clone(),
                source: repo.source.clone(),
                worktree,
                mount: repo.mount.clone(),
                branch: created.branch,
                base_commit: created.commit,
                host_gitfile,
                beads_snapshot,
                beads_bootstrap: Vec::new(),
            });
        }

        let ssh = self.paths.session_ssh_dir(&session_id);
        if let Err(error) = self.paths.create_session_ssh(&ssh) {
            self.cleanup_worktrees(&repos);
            let _ = std::fs::remove_dir_all(&session_dir);
            return Err(error).context("could not create session SSH credentials");
        }
        let ssh_agent_pid = match self.paths.start_session_ssh_agent(&ssh) {
            Ok(pid) => pid,
            Err(error) => {
                self.cleanup_worktrees(&repos);
                let _ = std::fs::remove_dir_all(&session_dir);
                return Err(error);
            }
        };
        let container_name = format!("jbox-{session_id}");
        let spec = match self.container_spec(
            &config,
            &repos,
            &container_name,
            &ssh,
            SessionLaunch {
                image: image.clone(),
                ssh_host: ssh_host.clone(),
                reuse_runtime_state: false,
            },
        ) {
            Ok(spec) => spec,
            Err(error) => {
                self.cleanup_worktrees(&repos);
                self.paths.stop_session_ssh_agent(ssh_agent_pid);
                let _ = std::fs::remove_dir_all(&session_dir);
                return Err(error);
            }
        };
        let port = match self.engine.start(&spec) {
            Ok(port) => port,
            Err(error) => {
                self.cleanup_worktrees(&repos);
                self.paths.stop_session_ssh_agent(ssh_agent_pid);
                let _ = std::fs::remove_dir_all(&session_dir);
                return Err(error);
            }
        };
        let known_hosts_tag = match self.paths.trust_session_host(&ssh_host, &session_id) {
            Ok(tag) => tag,
            Err(error) => {
                let _ = self.engine.stop(&container_name);
                self.paths.stop_session_ssh_agent(ssh_agent_pid);
                self.cleanup_worktrees(&repos);
                let _ = std::fs::remove_dir_all(&session_dir);
                return Err(error);
            }
        };
        // Capture the host-visible result of trusted bootstrap before a local
        // TUI can connect. Those files are jbox infrastructure, not agent
        // edits, and their exact digests remain the safety boundary.
        for repo in &mut repos {
            repo.beads_bootstrap = self.git.capture_beads_bootstrap(&repo.worktree);
        }

        let now = Utc::now();
        let session = Session {
            version: 1,
            id: session_id.clone(),
            state: SessionState::Running,
            container_name,
            ssh_host: ssh_host.clone(),
            ssh_port: port,
            ssh_agent_pid,
            known_hosts_tag,
            created_at: now,
            last_activity_at: now,
            ttl_seconds: config.resources.ttl_seconds,
            config_path: config.path,
            launch_directory: Some(launch_directory),
            image,
            repos,
            jcode_default_provider: config.jcode.default_provider.clone(),
            jcode_default_model: config.jcode.default_model.clone(),
        };
        self.state.save(&session)?;
        println!("jbox session {session_id} is running on {ssh_host}:{port}");
        Ok(session_id)
    }

    fn container_spec(
        &self,
        config: &Config,
        repos: &[RepoState],
        name: &str,
        ssh: &Path,
        launch: SessionLaunch,
    ) -> Result<ContainerSpec> {
        let mut mounts = Vec::new();
        let mut environment = Vec::new();
        for repo in repos {
            mounts.push((repo.worktree.clone(), safe_target(&repo.mount)?, true));
        }
        // Each worktree contains a jbox-snapshotted `.beads/issues.jsonl` when
        // its source repository uses Beads. The guest imports that portable
        // task context into its own writable Beads database before Jcode
        // starts, never exposing the host database or its locks/secrets.
        let beads_workspaces = repos
            .iter()
            .filter(|repo| repo.worktree.join(".beads/issues.jsonl").is_file())
            .collect::<Vec<_>>();
        if !beads_workspaces.is_empty() {
            environment.push((
                "JBOX_BEADS_WORKSPACE_COUNT".into(),
                beads_workspaces.len().to_string(),
            ));
            for (index, repo) in beads_workspaces.into_iter().enumerate() {
                environment.push((
                    format!("JBOX_BEADS_WORKSPACE_{index}"),
                    safe_target(&repo.mount)?.to_string_lossy().into_owned(),
                ));
                environment.push((format!("JBOX_BEADS_PREFIX_{index}"), repo.name.clone()));
            }
        }
        for mount in &config.mounts {
            mounts.push((
                mount
                    .source_path
                    .clone()
                    .context("configured mount source was not resolved")?,
                safe_target(&mount.target)?,
                mount.writable,
            ));
        }
        if config.jcode.persistent_credentials {
            for (source, target) in self.paths.jcode_credential_mounts()? {
                mounts.push((source, target, true));
            }
        }
        if config.jcode.default_provider.is_some()
            || config.jcode.default_model.is_some()
            || config.jcode.openai_reasoning_effort.is_some()
            || config.jcode.openai_service_tier.is_some()
        {
            let jcode_config = ssh
                .parent()
                .context("session SSH directory lacks a parent")?
                .join("runtime/jcode-config.toml");
            std::fs::create_dir_all(
                jcode_config
                    .parent()
                    .context("session Jcode configuration has no parent")?,
            )?;
            std::fs::write(&jcode_config, guest_jcode_config(&config.jcode))?;
            std::fs::set_permissions(&jcode_config, std::fs::Permissions::from_mode(0o600))?;
            // This nested, session-owned file mount intentionally overrides
            // only config.toml inside the dedicated credential-home mount.
            // Auth files remain in jbox-owned persistent credential state.
            mounts.push((
                jcode_config,
                PathBuf::from("/home/jbox/.jcode/config.toml"),
                true,
            ));
        }
        // This is deliberately session-scoped rather than credential-scoped.
        // Mounting a jcode external-provider directory beneath ~/.local/share
        // can cause Docker to create its parent directories as root, so the
        // unprivileged guest cannot create the daemon socket without this
        // explicit, jbox-owned runtime mount.
        let runtime = ssh
            .parent()
            .context("session SSH directory lacks a parent")?
            .join("runtime/jcode");
        std::fs::create_dir_all(&runtime)?;
        std::fs::set_permissions(&runtime, std::fs::Permissions::from_mode(0o700))?;
        mounts.push((
            runtime.clone(),
            PathBuf::from("/home/jbox/.local/share/jcode"),
            true,
        ));
        let jcode_session_hook = runtime.join("record-session");
        std::fs::write(
            &jcode_session_hook,
            "#!/bin/sh\nset -eu\numask 077\ncase \"${JCODE_HOOK_SESSION_ID:-}\" in\n  ''|*[!A-Za-z0-9_-]*) exit 0 ;;\nesac\nout=/home/jbox/.local/share/jcode/last-session-id\ntmp=\"${out}.tmp.$$\"\nprintf '%s\\n' \"$JCODE_HOOK_SESSION_ID\" > \"$tmp\"\nmv \"$tmp\" \"$out\"\n",
        )?;
        std::fs::set_permissions(&jcode_session_hook, std::fs::Permissions::from_mode(0o700))?;
        environment.push((
            "JCODE_HOOK_SESSION_START".into(),
            "/home/jbox/.local/share/jcode/record-session".into(),
        ));
        if let Some(instructions) = config.jcode.agent.instructions.as_deref() {
            let agent_instructions = ssh
                .parent()
                .context("session SSH directory lacks a parent")?
                .join("runtime/AGENTS.md");
            std::fs::write(
                &agent_instructions,
                format!("# Jbox session instructions\n\n{instructions}\n"),
            )?;
            std::fs::set_permissions(&agent_instructions, std::fs::Permissions::from_mode(0o600))?;
            // Jcode loads ~/AGENTS.md after the project AGENTS.md. Mounting a
            // session file here preserves the generated worktree unchanged.
            mounts.push((
                agent_instructions,
                PathBuf::from("/home/jbox/AGENTS.md"),
                false,
            ));
        }
        if !config.jcode.skills.is_empty() {
            // `gh skill` records source metadata at `.agents/.skill-lock.json`.
            // Mount the parent directory, not only `skills`, so the non-root
            // guest user can update that file while installing and refreshing
            // configured skills.
            let agents_dir = ssh
                .parent()
                .context("session SSH directory lacks a parent")?
                .join("runtime/agents");
            std::fs::create_dir_all(&agents_dir)?;
            std::fs::set_permissions(&agents_dir, std::fs::Permissions::from_mode(0o700))?;
            mounts.push((agents_dir, PathBuf::from("/home/jbox/.agents"), true));
            environment.push((
                "JBOX_SKILL_COUNT".into(),
                if launch.reuse_runtime_state {
                    // A session reaches Stopped only after its guest ran
                    // successfully. Its session-owned skills directory is
                    // therefore complete and can be reused without another
                    // network-bound `gh skill install` before SSH starts.
                    "0".into()
                } else {
                    config.jcode.skills.len().to_string()
                },
            ));
            if !launch.reuse_runtime_state {
                for (index, source) in config.jcode.skills.iter().enumerate() {
                    environment.push((
                        format!("JBOX_SKILL_{index}_REPOSITORY"),
                        source.repository.clone(),
                    ));
                    environment.push((
                        format!("JBOX_SKILL_{index}_NAME"),
                        source.skill.clone().unwrap_or_default(),
                    ));
                    environment.push((
                        format!("JBOX_SKILL_{index}_PIN"),
                        source.pin.clone().unwrap_or_default(),
                    ));
                    environment.push((
                        format!("JBOX_SKILL_{index}_ALLOW_HIDDEN"),
                        if source.allow_hidden_dirs { "1" } else { "0" }.into(),
                    ));
                }
            }
        }
        if config.git.network && config.git.credentials == "jbox" {
            mounts.push((
                self.paths.credentials.join("git").join("id_ed25519"),
                PathBuf::from("/home/jbox/.ssh/id_ed25519"),
                false,
            ));
        }
        if config.git.credentials == "github-cli" {
            mounts.push((
                self.paths.github_cli_hosts()?,
                PathBuf::from("/home/jbox/.config/gh/hosts.yml"),
                false,
            ));
            environment.push(("JBOX_GITHUB_CLI_CREDENTIALS".into(), "1".into()));
        }
        mounts.push((
            ssh.join("authorized_keys"),
            PathBuf::from("/home/jbox/.ssh/authorized_keys"),
            false,
        ));
        Ok(ContainerSpec {
            name: name.into(),
            image: launch.image,
            mounts,
            cpus: config.resources.cpus,
            memory: config.resources.memory.clone(),
            network: config.network.clone(),
            ssh_host: launch.ssh_host,
            environment,
        })
    }

