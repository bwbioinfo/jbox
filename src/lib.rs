    #[test]
    fn init_uses_an_existing_dockerfile_without_replacing_it() {
        let temp = tempdir().unwrap();
        assert!(
            Command::new("git")
                .args(["init", temp.path().to_str().unwrap()])
                .status()
                .unwrap()
                .success()
        );
        let dockerfile = temp.path().join(".jbox/Dockerfile");
        std::fs::create_dir_all(dockerfile.parent().unwrap()).unwrap();
        std::fs::write(&dockerfile, "FROM debian:bookworm-slim\n").unwrap();

        test_app(temp.path()).init(temp.path(), &[]).unwrap();
        assert_eq!(
            std::fs::read_to_string(dockerfile).unwrap(),
            "FROM debian:bookworm-slim\n"
        );
    }

    #[test]
    fn init_creates_a_missing_dockerfile_beside_existing_config() {
        let temp = tempdir().unwrap();
        assert!(
            Command::new("git")
                .args(["init", temp.path().to_str().unwrap()])
                .status()
                .unwrap()
                .success()
        );
        let config = temp.path().join(".jbox.toml");
        let original_config = "version = 1\n[workspace]\nmount = \"/workspace/custom\"\n";
        std::fs::write(&config, original_config).unwrap();

        test_app(temp.path())
            .init(temp.path(), &["ripgrep".into()])
            .unwrap();

        let updated_config = std::fs::read_to_string(&config).unwrap();
        assert!(updated_config.starts_with(original_config));
        assert!(updated_config.contains("[image]\ndockerfile = \".jbox/Dockerfile\""));
        assert_eq!(
            Config::load(temp.path())
                .unwrap()
                .0
                .image
                .dockerfile
                .as_deref(),
            Some(".jbox/Dockerfile")
        );
        let dockerfile = std::fs::read_to_string(temp.path().join(".jbox/Dockerfile")).unwrap();
        assert!(dockerfile.contains("FROM ${JBOX_BASE_IMAGE}"));
        assert!(dockerfile.contains("ripgrep"));
    }

    #[test]
    fn skills_repository_mount_includes_writable_gh_metadata_parent() {
        let temp = tempdir().unwrap();
        assert!(
            Command::new("git")
                .args(["init", temp.path().to_str().unwrap()])
                .status()
                .unwrap()
                .success()
        );
        std::fs::write(
            temp.path().join(".jbox.toml"),
            "version = 1\n[git]\ncredentials = 'github-cli'\n[[jcode.skills]]\nrepository = 'example/skills'\n[[jcode.skills]]\nrepository = 'K-Dense-AI/scientific-agent-skills'\nskill = 'scanpy'\n",
        )
        .unwrap();
        let (config, _) = Config::load(temp.path()).unwrap();
        let ssh = temp.path().join("session/ssh");
        std::fs::create_dir_all(&ssh).unwrap();
        let spec = test_app(temp.path())
            .container_spec(
                &config,
                &[],
                "jbox-test",
                &ssh,
                SessionLaunch {
                    image: "test-image".into(),
                    ssh_host: "127.0.0.2".into(),
                    reuse_runtime_state: false,
                },
            )
            .unwrap();

        assert!(
            spec.mounts
                .iter()
                .any(|(_, target, _)| { target == Path::new("/home/jbox/.agents") })
        );
        assert!(
            spec.environment
                .contains(&("JBOX_SKILL_COUNT".into(), "2".into(),))
        );
        assert!(
            spec.environment
                .contains(&("JBOX_SKILL_0_REPOSITORY".into(), "example/skills".into(),))
        );
        assert!(
            spec.environment
                .contains(&("JBOX_SKILL_0_NAME".into(), String::new(),))
        );
        assert!(
            spec.environment.contains(&(
                "JBOX_SKILL_1_REPOSITORY".into(),
                "K-Dense-AI/scientific-agent-skills".into(),
            ))
        );
        assert!(
            spec.environment
                .contains(&("JBOX_SKILL_1_NAME".into(), "scanpy".into(),))
        );

        let resumed = test_app(temp.path())
            .container_spec(
                &config,
                &[],
                "jbox-test",
                &ssh,
                SessionLaunch {
                    image: "test-image".into(),
                    ssh_host: "127.0.0.2".into(),
                    reuse_runtime_state: true,
                },
            )
            .unwrap();
        assert!(
            resumed
                .environment
                .contains(&("JBOX_SKILL_COUNT".into(), "0".into(),))
        );
        assert!(
            !resumed
                .environment
                .iter()
                .any(|(name, _)| name.starts_with("JBOX_SKILL_0_"))
        );
    }

